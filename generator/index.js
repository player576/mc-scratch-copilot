const fs = require('fs');
const path = require('path');
const os = require('os');
const { promisify } = require('util');
const mkdir = promisify(fs.mkdir);
const writeFile = promisify(fs.writeFile);
const exists = (p) => fs.promises.access(p).then(()=>true).catch(()=>false);

async function generate(xml, options) {
  const modid = (options && options.modid) || 'mc_scratch_mod';
  const modname = (options && options.modname) || 'ScratchMod';
  const tmp = path.join(process.cwd(), 'generated_projects');
  if (!await exists(tmp)) await mkdir(tmp, { recursive: true });
  const projectPath = path.join(tmp, modid);
  if (!await exists(projectPath)) await mkdir(projectPath, { recursive: true });

  // Basic package path
  const pkg = `com.example.${modid}`;
  const javaPath = path.join(projectPath, 'src', 'main', 'java', ...pkg.split('.'));
  const resourcesPath = path.join(projectPath, 'src', 'main', 'resources', 'assets', modid);
  await mkdir(javaPath, { recursive: true });
  await mkdir(resourcesPath, { recursive: true });

  // Parse simple generated JS output from Blockly
  const vm = require('vm');
  const jsCode = require('blockly').JavaScript.workspaceToCode(require('blockly').Xml.textToDom(xml) ? require('blockly').Xml.textToDom(xml) : '');
  // The above is not directly workable; instead re-generate code in a simple way: run the workspace XML through a small parser

  // Safer approach: scan xml for our blocks
  const items = [];
  const blocks = [];
  const onItemUses = [];
  const xmltext = xml;
  const itemRe = /<block type="create_item">[\s\S]*?<field name="ID">([^<]*)<\/field>[\s\S]*?<field name="NAME">([^<]*)<\/field>[\s\S]*?<field name="TEXTURE">([^<]*)<\/field>[\s\S]*?<\/block>/gmi;
  let m;
  while ((m = itemRe.exec(xmltext)) !== null) {
    items.push({ id: m[1], name: m[2], texture: m[3] });
  }
  const blockRe = /<block type="create_block">[\s\S]*?<field name="ID">([^<]*)<\/field>[\s\S]*?<field name="HARDNESS">([^<]*)<\/field>[\s\S]*?<field name="RES">([^<]*)<\/field>[\s\S]*?<\/block>/gmi;
  while ((m = blockRe.exec(xmltext)) !== null) {
    blocks.push({ id: m[1], hardness: m[2], resistance: m[3] });
  }
  const onItemRe = /<block type="on_item_use">[\s\S]*?<field name="ITEM">([^<]*)<\/field>[\s\S]*?<\/block>/gmi;
  while ((m = onItemRe.exec(xmltext)) !== null) {
    onItemUses.push({ item: m[1] });
  }

  // Write ModMain.java
  const modMain = `package ${pkg};

import net.fabricmc.api.ModInitializer; // placeholder - for Forge this will be replaced by templates

public class ${capitalize(modname)} {
    // Mod entry - generated by MC Scratch Copilot
}
`;
  await writeFile(path.join(javaPath, `${capitalize(modname)}.java`), modMain, 'utf8');

  // Write simple registry helper for items
  if (items.length) {
    const itemsJava = `package ${pkg};

public class ModItems {
` + items.map(it => `    // ${it.id}
    // texture: ${it.texture}
`).join('\n') + `}
`;
    await writeFile(path.join(javaPath, `ModItems.java`), itemsJava, 'utf8');

    // write placeholder texture files
    const texItemDir = path.join(projectPath, 'src', 'main', 'resources', 'assets', modid, 'textures', 'item');
    await mkdir(texItemDir, { recursive: true });
    for (const it of items) {
      const png = path.join(texItemDir, `${it.id}.png`);
      // write a 16x16 transparent PNG placeholder
      const emptyPng = Buffer.from('89504e470d0a1a0a0000000d49484452000000100000001008060000001f' +
        'f3ff610000000467414d410000b18f0bfc6105000000097048597300000ec4' +
        '00000ec401952b0e1b0000000749444154789c63600000020001005fe02f0a' +
        '0000000049454e44ae426082', 'hex');
      await writeFile(png, emptyPng);
    }
  }

  // resources/lang
  const langDir = path.join(projectPath, 'src', 'main', 'resources', 'assets', modid, 'lang');
  await mkdir(langDir, { recursive: true });
  const lang = { "itemGroup.${modid}.tab": modname };
  for (const it of items) {
    lang[`${modid}.item.${it.id}`] = it.name;
  }
  await writeFile(path.join(langDir, 'en_us.json'), JSON.stringify(lang, null, 2), 'utf8');

  // write a README and a placeholder build.gradle instructing to place MDK
  const readme = `This generated project contains sources for modid ${modid}.

To build:\n1) Download the official Forge MDK 1.20.1 (place contents of the MDK into this folder so that gradlew exists), or set FORGE_MDK_ZIP env and use the provided scripts to extract it.\n2) Run ./gradlew build\n`;
  await writeFile(path.join(projectPath, 'README_BUILDTOOL.txt'), readme, 'utf8');

  // Write a minimal settings.gradle and build.gradle placeholders to make the folder recognizable
  const settings = `rootProject.name = "${modid}"
`;
  await writeFile(path.join(projectPath, 'settings.gradle'), settings, 'utf8');
  const buildGradle = `// Placeholder build.gradle\n// This generated folder is intended to be merged with the official Forge MDK 1.20.1.\n`;
  await writeFile(path.join(projectPath, 'build.gradle'), buildGradle, 'utf8');

  return { projectPath };
}

function capitalize(s){ return s.charAt(0).toUpperCase() + s.slice(1); }

module.exports = { generate };
